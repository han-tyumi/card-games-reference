/**
 * Generate rendered/ Markdown from the JSON entries in games/.
 *
 * Everything under rendered/ is generated output: edit the JSON, then re-run
 * this. Hand edits to rendered/ will be overwritten.
 *
 *   npm run render                      # write rendered/
 *   npm run render -- --check           # fail if rendered/ is stale (CI gate)
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import type { CardGame } from "naibi";
import {
  BACKGROUND_HEADING,
  SECTIONS,
  categoryLabel,
  facts,
  gamesByCategory,
  loadGames,
  renderDiagramSvg,
  renderFigureSvg,
} from "naibi";
import { DIAGRAM_DIR, RENDERED_DIR } from "./paths.ts";

/** Hand size per player count, plus anything stripped from the deck. */
export function dealTable(deal: NonNullable<CardGame["deal"]>): string[] {
  const hasRemoved = deal.some((row) => row.removed);
  const hasNote = deal.some((row) => row.note);

  const header = ["Players", "Each player gets"];
  if (hasRemoved) header.push("Removed from the deck");
  if (hasNote) header.push("Notes");

  const lines = [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
  ];

  for (const row of deal) {
    const cells = [
      String(row.players),
      row.hand === 0 ? "the whole deck, shared out" : `${row.hand} cards`,
    ];
    if (hasRemoved) cells.push(row.removed ?? "—");
    if (hasNote) cells.push(row.note ?? "—");
    lines.push(`| ${cells.join(" | ")} |`);
  }

  return lines;
}

/** Point values, for looking up mid-hand. */
export function scoringTable(table: NonNullable<CardGame["scoring_table"]>): string[] {
  const hasNote = table.some((row) => row.note);
  const header = hasNote ? ["Scores", "Value", "Notes"] : ["Scores", "Value"];

  const lines = [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
  ];

  for (const row of table) {
    const cells = [row.item, row.value];
    if (hasNote) cells.push(row.note ?? "—");
    lines.push(`| ${cells.join(" | ")} |`);
  }

  return lines;
}

const banner = (source: string) =>
  `<!-- Generated by packages/build/render-markdown.ts from ${source}. Do not edit by hand. -->`;

export function renderGame(game: CardGame): string {
  const lines: string[] = [banner(`games/${game.id}.json`), "", `# ${game.name}`, ""];

  for (const [label, value] of facts(game)) {
    lines.push(`**${label}:** ${value}  `);
  }
  lines.push("");

  for (const { key, heading } of SECTIONS) {
    lines.push(`## ${heading}`, "", game[key], "");

    // Each aid sits with the prose it supports, rather than in a gallery of
    // its own at the bottom that nobody scrolls to mid-game.
    if (key === "setup") {
      if (game.layout) {
        lines.push(`![${game.name} setup diagram](diagrams/${game.id}.svg)`, "");
      }
      if (game.deal) lines.push(...dealTable(game.deal), "");
    }

    if (key === "play" && game.figures) {
      game.figures.forEach((_, index) => {
        lines.push(
          `![${game.name} card figure](diagrams/${game.id}-fig${index + 1}.svg)`,
          "",
        );
      });
    }

    if (key === "goal_and_scoring" && game.scoring_table) {
      lines.push(...scoringTable(game.scoring_table), "");
    }
  }

  lines.push("## Variants", "");
  for (const variant of game.variants) {
    lines.push(`**${variant.name}** — ${variant.description}`, "");
  }

  if (game.background) {
    lines.push(`## ${BACKGROUND_HEADING}`, "", game.background, "");
  }

  if (game.tags.length > 0) {
    lines.push(`**Tags:** ${[...game.tags].sort().join(", ")}`, "");
  }

  lines.push(
    `*Rules checked against: ${game.sources_consulted.join(", ")}.*`,
    "",
    "---",
    "",
    "Part of [Naibi](../README.md). Text licensed [CC BY-SA 4.0](../LICENSE).",
    "",
  );

  return lines.join("\n");
}

export function renderIndex(games: CardGame[]): string {
  const lines: string[] = [
    banner("games/*.json"),
    "",
    "# Card Game Rules — Index",
    "",
    `${games.length} games, free to reuse under CC BY-SA 4.0.`,
    "",
  ];

  for (const [category, entries] of gamesByCategory(games)) {
    lines.push(
      `## ${categoryLabel(category)}`,
      "",
      "| Game | Players | Deck | Time | Difficulty |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const game of entries) {
      const row = Object.fromEntries(facts(game));
      lines.push(
        `| [${game.name}](${game.id}.md) | ${row["Players"]} | ${row["Deck"]} ` +
          `| ${row["Time"]} | ${row["Difficulty"]} |`,
      );
    }
    lines.push("");
  }

  return lines.join("\n");
}

function main(): number {
  const check = process.argv.includes("--check");

  const games = loadGames();
  if (games.length === 0) {
    console.error("No games found. Nothing to render.");
    return 1;
  }

  const wanted = new Map<string, string>();
  for (const game of games) wanted.set(`${game.id}.md`, renderGame(game));
  wanted.set("index.md", renderIndex(games));

  // Diagrams live beside the Markdown that embeds them, and are regenerated
  // from the same data, so they cannot go stale independently.
  const diagrams = new Map<string, string>();
  for (const game of games) {
    if (game.layout) {
      diagrams.set(`${game.id}.svg`, renderDiagramSvg(game.layout, game.name));
    }
    game.figures?.forEach((figure, index) => {
      diagrams.set(
        `${game.id}-fig${index + 1}.svg`,
        renderFigureSvg(figure, game.name),
      );
    });
  }

  mkdirSync(RENDERED_DIR, { recursive: true });
  mkdirSync(DIAGRAM_DIR, { recursive: true });

  const existing = readdirSync(RENDERED_DIR).filter((name) => name.endsWith(".md"));
  const existingDiagrams = existsSync(DIAGRAM_DIR)
    ? readdirSync(DIAGRAM_DIR).filter((name) => name.endsWith(".svg"))
    : [];

  if (check) {
    const stale: string[] = [];
    for (const [name, content] of [...wanted].sort()) {
      const path = join(RENDERED_DIR, name);
      if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
        stale.push(name);
      }
    }
    for (const [name, content] of [...diagrams].sort()) {
      const path = join(DIAGRAM_DIR, name);
      if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
        stale.push(`diagrams/${name}`);
      }
    }

    const orphans = [
      ...existing.filter((name) => !wanted.has(name)),
      ...existingDiagrams
        .filter((name) => !diagrams.has(name))
        .map((name) => `diagrams/${name}`),
    ];

    if (stale.length > 0 || orphans.length > 0) {
      for (const name of stale) console.log(`stale: rendered/${name}`);
      for (const name of orphans) {
        console.log(`orphaned: rendered/${name} has no matching game entry`);
      }
      console.log("\nRun: npm run render");
      return 1;
    }
    console.log(
      `rendered/ is up to date (${wanted.size} files, ${diagrams.size} diagrams).`,
    );
    return 0;
  }

  for (const [name, content] of [...wanted].sort()) {
    writeFileSync(join(RENDERED_DIR, name), content, "utf8");
  }
  for (const [name, content] of [...diagrams].sort()) {
    writeFileSync(join(DIAGRAM_DIR, name), content, "utf8");
  }

  for (const name of existing) {
    if (!wanted.has(name)) {
      rmSync(join(RENDERED_DIR, name));
      console.log(`removed stale rendered/${name}`);
    }
  }
  for (const name of existingDiagrams) {
    if (!diagrams.has(name)) {
      rmSync(join(DIAGRAM_DIR, name));
      console.log(`removed stale rendered/diagrams/${name}`);
    }
  }

  console.log(
    `Wrote ${wanted.size} files to rendered/ (${games.length} games + index), ` +
      `${diagrams.size} diagrams.`,
  );
  return 0;
}

// Only when run as a command. Imported -- by the tests -- this file is just
// the renderers above.
if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  process.exit(main());
}
